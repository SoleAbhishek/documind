import os
import tempfile
from dataclasses import dataclass, field
from typing import List, Dict, Any, Optional
import pypdf

from src.config import settings


@dataclass
class ParsedPage:
    """Represents a single parsed page from a document."""
    page_number: int
    text: str  # Formatted Markdown text (with preserved tables and headers)
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ParsedDocument:
    """Represents the complete parsed document output."""
    filename: str
    pages: List[ParsedPage]
    total_pages: int
    parser_used: str  # "llamaparse", "local_pypdf", or "plain_text"

    @property
    def full_markdown(self) -> str:
        """Returns the full document combined as a single continuous Markdown string."""
        return "\n\n".join(page.text for page in self.pages if page.text.strip())


class DocumentParser:
    """
    Enterprise Document Parsing & OCR Service.
    
    Architecture:
    1. Primary Parser: LlamaParse (Cloud OCR)
       - Uses multimodal vision to detect tables, complex layouts, and scanned text.
       - Converts visual structures directly into clean Markdown tables (| col1 | col2 |).
    2. Fallback Parser: PyPDF (Local)
       - Runs 100% locally with zero API dependency if running offline or if API key is absent.
    3. Text Parser:
       - Direct UTF-8 decoding for .txt and .md files.
    """

    def __init__(self):
        self.llama_api_key = settings.LLAMA_CLOUD_API_KEY
        self._is_llama_configured = bool(
            self.llama_api_key and not self.llama_api_key.startswith("llx-your")
        )

    def parse_bytes(self, file_bytes: bytes, filename: str) -> ParsedDocument:
        """
        Main entry point for parsing an uploaded document from raw bytes.
        """
        ext = os.path.splitext(filename)[1].lower()

        # Handle plain text / markdown files directly
        if ext in [".txt", ".md", ".csv", ".json"]:
            return self._parse_text(file_bytes, filename)

        # Handle PDF files
        if ext == ".pdf":
            # If LlamaParse API key is available, use cloud OCR
            if self._is_llama_configured:
                try:
                    return self._parse_pdf_llamaparse(file_bytes, filename)
                except Exception as e:
                    print(f"[Parser] Warning: LlamaParse failed ({e}). Falling back to local PyPDF parser.")

            # Fallback to local PyPDF parser
            return self._parse_pdf_local(file_bytes, filename)

        # Default fallback for unknown text formats
        return self._parse_text(file_bytes, filename)

    def _parse_pdf_llamaparse(self, file_bytes: bytes, filename: str) -> ParsedDocument:
        """
        Parses PDF using LlamaParse for high-fidelity OCR and table extraction into Markdown.
        """
        from llama_parse import LlamaParse

        # LlamaParse requires a file path on disk, so we write bytes to a secure temp file
        with tempfile.NamedTemporaryFile(suffix=".pdf", delete=False) as temp_file:
            temp_path = temp_file.name
            temp_file.write(file_bytes)

        try:
            print(f"[Parser] Parsing '{filename}' with LlamaParse OCR...")
            parser = LlamaParse(
                api_key=self.llama_api_key,
                result_type="markdown",  # Output format: clean structured Markdown
                num_workers=4,
                verbose=False,
                language="en"
            )

            # Synchronous call to parse document
            documents = parser.load_data(temp_path)

            pages: List[ParsedPage] = []
            for idx, doc in enumerate(documents, start=1):
                # doc.text contains Markdown generated by LlamaParse
                # LlamaParse preserves tables as Markdown (| col1 | col2 |)
                page_text = doc.text.strip()
                page_num = doc.metadata.get("page", idx) if hasattr(doc, "metadata") else idx
                
                pages.append(ParsedPage(
                    page_number=page_num,
                    text=page_text,
                    metadata={"source": filename, "parser": "llamaparse"}
                ))

            print(f"[Parser] LlamaParse successfully parsed {len(pages)} pages for '{filename}'.")
            return ParsedDocument(
                filename=filename,
                pages=pages,
                total_pages=len(pages),
                parser_used="llamaparse"
            )

        finally:
            # Clean up temporary file from disk
            if os.path.exists(temp_path):
                os.remove(temp_path)

    def _parse_pdf_local(self, file_bytes: bytes, filename: str) -> ParsedDocument:
        """
        Local PDF fallback using PyPDF. Fast, offline, with zero external dependencies.
        """
        import io
        print(f"[Parser] Parsing '{filename}' with local PyPDF extractor...")
        
        pdf_file = io.BytesIO(file_bytes)
        reader = pypdf.PdfReader(pdf_file)
        
        pages: List[ParsedPage] = []
        for idx, page in enumerate(reader.pages, start=1):
            text = page.extract_text() or ""
            pages.append(ParsedPage(
                page_number=idx,
                text=text.strip(),
                metadata={"source": filename, "parser": "local_pypdf"}
            ))

        print(f"[Parser] Local PyPDF parsed {len(pages)} pages for '{filename}'.")
        return ParsedDocument(
            filename=filename,
            pages=pages,
            total_pages=len(pages),
            parser_used="local_pypdf"
        )

    def _parse_text(self, file_bytes: bytes, filename: str) -> ParsedDocument:
        """
        Parses plain text / markdown files by decoding UTF-8.
        """
        text = file_bytes.decode("utf-8", errors="replace")
        page = ParsedPage(
            page_number=1,
            text=text,
            metadata={"source": filename, "parser": "plain_text"}
        )
        return ParsedDocument(
            filename=filename,
            pages=[page],
            total_pages=1,
            parser_used="plain_text"
        )


# Global singleton parser instance
document_parser = DocumentParser()
